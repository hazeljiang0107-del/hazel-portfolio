#!/usr/bin/env python3
"""
Web-weight copies of the case-study images used by the redesign (Alfa Romeo IVI, Zingerman's,
Still Here, Echoes). Originals in public/assets/** are never modified; each gets:

  public/assets/redesign/cs/<project>/<name>.webp         display size (max 1600 wide, phones 640 wide)
  public/assets/redesign/cs/<project>/<name>-full.webp    larger copy for the lightbox (only if it is larger)

and src/data/redesignMedia.js is regenerated with { original path: { src, full, w, h } }.

    python3 scripts/build-redesign-media.py
"""
import json
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUB = os.path.join(ROOT, 'public')
OUT_DIR = '/assets/redesign/cs'

SOURCES = {
    'stellantis': ['stellantis'],
    'zingerman': ['zingerman'],
    'still-here': ['still-here'],
    'echoes': ['echoes'],
}
EXTRA = {
    '/assets/echoes-hero.jpg': 'echoes',
    '/assets/still-here-hero.jpg': 'still-here',
    '/assets/zingerman-hero.jpg': 'zingerman',
}
SKIP_DIRS = ('demo',)


def collect():
    found = {}
    for project, dirs in SOURCES.items():
        for d in dirs:
            base = os.path.join(PUB, 'assets', d)
            for dp, dn, fn in os.walk(base):
                dn[:] = [x for x in dn if x not in SKIP_DIRS]
                for f in fn:
                    if f.lower().endswith(('.png', '.jpg', '.jpeg')):
                        rel = '/' + os.path.relpath(os.path.join(dp, f), PUB).replace(os.sep, '/')
                        found[rel] = project
    found.update(EXTRA)
    return found


def fit(im, max_w, max_h):
    w, h = im.size
    s = min(1.0, max_w / w, max_h / h)
    return im if s >= 1 else im.resize((max(1, round(w * s)), max(1, round(h * s))), Image.LANCZOS)


def save(im, path, q):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    im.save(path, 'WEBP', quality=q, method=6)
    return os.path.getsize(path)


def main():
    manifest = {}
    total = 0
    for orig, project in sorted(collect().items()):
        im = Image.open(os.path.join(PUB, orig.lstrip('/')))
        if im.mode not in ('RGB', 'RGBA'):
            im = im.convert('RGBA' if 'A' in im.mode else 'RGB')
        w, h = im.size
        phone = h / w > 1.6
        disp = fit(im, 640 if phone else 1600, 1400 if phone else 1000)
        name = os.path.splitext(os.path.basename(orig))[0]
        folder = f'{project}/'
        prefix = f'/assets/{project}/'
        if orig.startswith(prefix) and '/' in orig[len(prefix):]:
            folder += orig[len(prefix):].rsplit('/', 1)[0] + '/'
        rel = f'{OUT_DIR}/{folder}{name}.webp'
        total += save(disp, os.path.join(PUB, rel.lstrip('/')), 80)
        entry = {'src': rel, 'w': disp.size[0], 'h': disp.size[1]}
        full = fit(im, 2400, 2600)
        if full.size[0] > disp.size[0] * 1.15:
            frel = f'{OUT_DIR}/{folder}{name}-full.webp'
            total += save(full, os.path.join(PUB, frel.lstrip('/')), 82)
            entry['full'] = frel
        manifest[orig] = entry
    js = (
        '/* Generated by scripts/build-redesign-media.py: do not edit.\n'
        ' * original path -> web-weight copy (src), optional larger lightbox copy (full), display size (w, h). */\n'
        'export const IMG = ' + json.dumps(manifest, indent=2) + '\n'
    )
    with open(os.path.join(ROOT, 'src', 'data', 'redesignMedia.js'), 'w') as f:
        f.write(js)
    print(f'{len(manifest)} images, {total / 1e6:.1f} MB of webp written')


if __name__ == '__main__':
    main()
